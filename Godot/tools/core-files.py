"""
Finds which of Gothic-Unity's core files compile for Godot (with Port/UnityShim) and writes them into
Port/GothicCore/GothicCore.csproj. Start set: files without Unity scene types plus the model "seam" files; every
build drops the files that still have errors, until the project builds. Prints what cost the most files.

Usage: python3 tools/core-files.py [--report]
"""
import collections
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SCRIPTS = os.path.abspath(os.path.join(ROOT, "..", "Assets", "Gothic-Core", "Scripts"))
PROJECT = os.path.join(ROOT, "Port", "GothicCore", "GothicCore.csproj")
DOTNET = os.path.expanduser("~/opt/dotnet/dotnet")

SCENE = {"GameObject", "Transform", "MonoBehaviour", "Component", "Resources", "Mesh", "Material", "Texture2D",
         "Texture", "Shader", "Renderer", "MeshRenderer", "SkinnedMeshRenderer", "MeshFilter", "Collider",
         "BoxCollider", "MeshCollider", "CapsuleCollider", "SphereCollider", "Rigidbody", "Physics", "AudioSource",
         "AudioClip", "Light", "Camera", "Coroutine", "WaitForSeconds", "Animator", "ParticleSystem", "SceneManager",
         "Application", "Canvas", "RectTransform", "Sprite", "Image", "Button", "Graphics", "RenderTexture",
         "Behaviour", "ScriptableObject", "PlayerPrefs", "Screen", "Input", "LineRenderer", "TextMeshPro", "TMP_Text",
         "LODGroup", "Terrain", "CharacterController", "Collision", "Joint", "AnimationClip", "NativeArray"}
SEAMS = ["Models/Container/NpcContainer.cs", "Models/Container/VobContainer.cs",
         "Adapters/Properties/AbstractProperties.cs", "Adapters/Properties/NpcProperties.cs",
         "Adapters/Properties/VobProperties.cs", "Adapters/Properties/VobSpotProperties.cs",
         "Adapters/Npc/NpcPrefabProperties.cs", "Logging/Logger.cs"]
SEAMS += ["Adapters/Properties/Vobs/" + f for f in os.listdir(os.path.join(SCRIPTS, "Adapters/Properties/Vobs"))
          if f.endswith(".cs")]

HEADER = """<Project Sdk="Microsoft.NET.Sdk">
  <!-- Gothic-Unity's engine-free core, compiled for Godot straight from Assets/Gothic-Core/Scripts (no copies), so
       upstream work comes along with a merge. Generated by tools/core-files.py: files that still need Unity scene
       objects stay out until they are moved behind interfaces upstream. -->
  <PropertyGroup>
    <TargetFramework>netstandard2.1</TargetFramework>
    <LangVersion>9</LangVersion>
    <Nullable>disable</Nullable>
    <AssemblyName>Gothic.Core</AssemblyName>
    <RootNamespace>Gothic.Core</RootNamespace>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <NoWarn>CS0414;CS0649;CS0169;CS0067;CS8632;CS0618</NoWarn>
    <CoreScripts>$(MSBuildThisFileDirectory)../../../Assets/Gothic-Core/Scripts</CoreScripts>
  </PropertyGroup>

  <ItemGroup>
    <ProjectReference Include="../UnityShim/UnityShim.csproj" />
    <Reference Include="ZenKit"><HintPath>../../lib/ZenKit.dll</HintPath></Reference>
    <Reference Include="DirectMusic"><HintPath>../../lib/DirectMusic.dll</HintPath></Reference>
    <PackageReference Include="Newtonsoft.Json" Version="13.0.3" />
    <PackageReference Include="JetBrains.Annotations" Version="2024.3.0" />
  </ItemGroup>

  <ItemGroup>
"""
FOOTER = """  </ItemGroup>
</Project>
"""


def candidates():
    tokens = re.compile(r"\b([A-Z][A-Za-z0-9_]+)\b")
    result = []
    for directory, _, files in os.walk(SCRIPTS):
        for name in files:
            if not name.endswith(".cs"):
                continue
            path = os.path.relpath(os.path.join(directory, name), SCRIPTS)
            source = open(os.path.join(directory, name), encoding="utf-8", errors="ignore").read()
            if any(n in source for n in ("Unity.Burst", "Unity.Jobs", "Unity.Collections", "Unity.Mathematics",
                                         "UnityEditor")):
                continue
            if "UnityEngine" in source and set(tokens.findall(source)) & SCENE:
                continue
            result.append(path)
    return sorted(set(result) | set(SEAMS))


def write(files):
    items = "".join(f'    <Compile Include="$(CoreScripts)/{f}" Link="Core/{f}" />\n' for f in sorted(files))
    open(PROJECT, "w").write(HEADER + items + FOOTER)


def build():
    out = subprocess.run([DOTNET, "build", "-nologo", "-v", "q", PROJECT], capture_output=True, text=True,
                         env={**os.environ, "DOTNET_NOLOGO": "1"}).stdout
    errors = collections.defaultdict(list)
    for line in out.splitlines():
        match = re.search(r"Gothic-Core/Scripts/(.+?\.cs)\(\d+,\d+\): error (CS\d+): (.*?) \[", line)
        if match:
            errors[match.group(1)].append((match.group(2), match.group(3)))
    return errors


def main():
    files = set(candidates())
    start = len(files)
    first_errors = None
    excluded = {}
    while True:
        write(files)
        errors = build()
        if first_errors is None:
            first_errors = errors
        if not errors:
            break
        for path, problems in errors.items():
            files.discard(path)
            excluded.setdefault(path, problems[0])
    print(f"{len(files)} of {start} start files compile ({len(excluded)} dropped)")
    if "--report" in sys.argv:
        reasons = collections.Counter()
        for problems in first_errors.values():
            for code, message in set(problems):
                key = re.sub(r"'[^']*'", lambda m: m.group(0) if "Unity" in m.group(0) or "Vector" in m.group(0)
                             or "Quaternion" in m.group(0) or "Mathf" in m.group(0) else "'X'", message)
                reasons[f"{code} {key}"[:110]] += 1
        print("first build, most common errors (files):")
        for reason, count in reasons.most_common(15):
            print(f"  {count:3} {reason}")


main()
